"""The guide's "MCP tools reference" is generated from the registered tools.

Between the ``mcp-tools-reference`` markers in ``docs/guide/README.md`` the
guide holds, for every tool the broker registers, its credential, its inputs
(from the JSON schema) and its description (the docstring an agent sees). This
test renders that block and compares; a new tool, parameter or docstring change
fails it until the guide is regenerated:

    SW_WRITE_GUIDE=1 pytest tests/unit/test_guide_mcp_reference.py

Credentials are not in the schema, so ``CREDENTIALS`` names one per tool; a
tool without an entry fails the test.
"""
