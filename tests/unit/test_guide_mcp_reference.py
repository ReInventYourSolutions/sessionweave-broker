def _type(prop: dict[str, Any]) -> str:
    if "enum" in prop:
        return " \\| ".join(f'"{v}"' for v in prop["enum"])
    if "anyOf" in prop:
        return " \\| ".join(_type(p) for p in prop["anyOf"] if p.get("type") != "null")
    t = prop.get("type", "any")
    if t == "array":
        return f"array of {_type(prop.get('items', {}))}"
    return str(t)


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _tool_block(tool: Any) -> list[str]:
    schema = tool.input_schema
    required = set(schema.get("required", []))
    lines = [f"#### `{tool.name}`", "", f"Credential: {CREDENTIALS[tool.name]}.", ""]
    props: dict[str, Any] = schema.get("properties", {})
    if props:
        lines += ["| input | type | required | description |", "|---|---|---|---|"]
        for name, prop in props.items():
            req = "yes" if name in required else "no"
            lines.append(
                f"| `{name}` | {_cell(_type(prop))} | {req} | "
                f"{_cell(str(prop.get('description', '')))} |"
            )
    else:
        lines.append("No inputs.")
    lines += ["", (tool.description or "").strip(), ""]
    return lines


def render() -> str:
    mcp = _build_fastmcp(MagicMock(), HandleRegistry())
    tools = {t.name: t for t in asyncio.run(mcp.list_tools())}
    missing = sorted(set(tools) - set(CREDENTIALS))
    assert not missing, f"name a credential in CREDENTIALS for: {missing}"
    out = [
        BEGIN,
        "",
        f"The broker registers {len(tools)} tools. Errors come back as an MCP tool error "
        "whose text is `<code>: <message>`; the codes are listed in "
        "[§12](#12-error-codes).",
        "",
    ]
    seen: set[str] = set()
    for title, prefixes in GROUPS:
        names = sorted(n for n in tools if n.startswith(prefixes) and n not in seen)
        seen.update(names)
        out += [f"### {title}", ""]
        for name in names:
            out += _tool_block(tools[name])
    assert seen == set(tools), f"tools in no group: {sorted(set(tools) - seen)}"
    out.append(END)
    return "\n".join(out)


def test_guide_mcp_reference_is_current() -> None:
    text = GUIDE.read_text(encoding="utf-8")
    assert BEGIN in text and END in text, "the guide lost its mcp-tools-reference markers"
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    expected = render()
    current = BEGIN + rest.split(END, 1)[0] + END
    if current != expected and os.environ.get("SW_WRITE_GUIDE") == "1":
        GUIDE.write_text(head + expected + tail, encoding="utf-8")
        return
    assert current == expected, (
        "docs/guide/README.md MCP tools reference is stale; regenerate with "
        "SW_WRITE_GUIDE=1 pytest tests/unit/test_guide_mcp_reference.py"
    )
